type AdapterFactory = ReturnType<typeof memoryAdapter>;
type Adapter = ReturnType<AdapterFactory>;

/**
 * Makes account updates fail on demand at the adapter level: `account.update` throws before
 * writing, `account.update.after-commit` writes and then throws (like a failing after-write
 * step). Database hooks cannot simulate these because the credential switch bypasses them.
 */
function withAccountUpdateFaults(
  factory: AdapterFactory,
  faults: ReadonlySet<FaultPoint>,
): AdapterFactory {
  return ((options: BetterAuthOptions) => {
    const adapter = factory(options);
    const update = async (args: Parameters<Adapter["update"]>[0]) => {
      if (args.model === "account" && faults.has("account.update")) {
        throw new Error("injected failure: account.update");
      }
      const updated = await adapter.update(args);
      if (args.model === "account" && faults.has("account.update.after-commit")) {
        throw new Error("injected failure: account.update.after-commit");
      }
      return updated;
    };
    return { ...adapter, update: update as Adapter["update"] };
  }) as AdapterFactory;
}

/**
 * Turns transactions off, like adapters that cannot roll back (the Convex adapter declares
 * `transaction: false`). Better Auth then runs "transactions" as-is.
 */
function withoutTransactions(factory: AdapterFactory): AdapterFactory {
  return ((options: BetterAuthOptions) => {
    const adapter = factory(options);
    const nonTransactional: Adapter = {
      ...adapter,
      options: {
        ...adapter.options,
        adapterConfig: { ...adapter.options?.adapterConfig, transaction: false },
      },
      transaction: (callback) => callback(nonTransactional),
    } as Adapter;
    return nonTransactional;
  }) as AdapterFactory;
}

export type AuthUnderTest = ReturnType<typeof createTestAuth>;

/** Builds Better Auth with the memory adapter and the OPAQUE plugin. */
export function createTestAuth(input: {
  db: MemoryDb;
  opaque: OpaqueOptions;
  transactions?: boolean;
  faults?: ReadonlySet<FaultPoint>;
  options?: Partial<BetterAuthOptions>;
}) {
  let database = withAccountUpdateFaults(memoryAdapter(input.db), input.faults ?? new Set());
  if (input.transactions === false) {
    database = withoutTransactions(database);
  }
  return betterAuth({
    baseURL: BASE_URL,
    secret: SECRET,
    database,
    rateLimit: { enabled: false },
    logger: { disabled: true },
    ...input.options,
    plugins: [opaque(input.opaque)],
  });
}

/** A captured request: everything the client sent over the network. */
export type CapturedRequest = { url: string; body: string };

/**
 * A real Better Auth client with the OPAQUE client plugin whose `fetch` calls `auth.handler`
 * directly. It keeps its own cookie jar (one browser) and records every request body.
 */
export function createTestClient(
  auth: { handler: (request: Request) => Promise<Response> },
  options?: OpaqueClientOptions,
) {
  const cookies = new Map<string, string>();
  const requests: CapturedRequest[] = [];
  const responses: CapturedRequest[] = [];

  const customFetchImpl = async (input: string | URL | Request, init?: RequestInit) => {
    const request = new Request(input, init);
    const body = await request.clone().text();
    requests.push({ url: request.url, body });

    const headers = new Headers(request.headers);
    headers.set("origin", BASE_URL);
    if (cookies.size > 0) {
      headers.set("cookie", [...cookies].map(([name, value]) => `${name}=${value}`).join("; "));
    }
    const response = await auth.handler(new Request(request, { headers }));
    responses.push({ url: request.url, body: await response.clone().text() });

    for (const setCookie of response.headers.getSetCookie()) {
      const [pair = "", ...attributes] = setCookie.split(";");
      const separator = pair.indexOf("=");
      const name = pair.slice(0, separator).trim();
      const value = pair.slice(separator + 1).trim();
      const expired = attributes.some(
        (attribute) => attribute.trim().toLowerCase() === "max-age=0",
      );
      if (value === "" || expired) {
        cookies.delete(name);
      } else {
        cookies.set(name, value);
      }
    }
    return response;
  };

  const authClient = createAuthClient({
    baseURL: BASE_URL,
    plugins: [opaqueClient(options), twoFactorClient()],
    fetchOptions: { customFetchImpl },
  });

  return { authClient, requests, responses, cookies };
}

export type TestClient = ReturnType<typeof createTestClient>;

/** Asserts that none of the given secrets (passwords, export keys) appears in any request body. */
export function expectNotSent(clients: TestClient[], secrets: string[]): void {
  for (const { requests } of clients) {
    expect(requests.length).toBeGreaterThan(0);
    for (const request of requests) {
      for (const secret of secrets) {
        expect(request.body).not.toContain(secret);
      }
    }
  }
}

/** Raw JSON POST through `auth.handler`, for checks below the client plugin. */
export async function postJson(
  auth: { handler: (request: Request) => Promise<Response> },
  path: string,
  body: unknown,
  headers?: Record<string, string>,
): Promise<{ status: number; body: Record<string, unknown> | null }> {
  const response = await auth.handler(
    new Request(`${BASE_URL}/api/auth${path}`, {
      method: "POST",
      headers: { "content-type": "application/json", origin: BASE_URL, ...headers },
      body: JSON.stringify(body),
    }),
  );
  const text = await response.text();
  return { status: response.status, body: text ? JSON.parse(text) : null };
}

export type FaultPoint =
  | "validatePayload"
  | "commitPayload"
  | "activatePayload"
  | "loadPayload"
  | "user.create"
  | "account.create"
  | "account.create.rejected"
  | "account.update"
  | "account.update.after-commit"
  | "session.create";

/** Hooks a test can hold open to interleave concurrent flows deterministically. */
export type PausePoint = "commitPayload" | "loadPayload";

/**
 * An app-side payload store implementing the hooks the way the contract asks (payloads per
 * credential version, only the previous version removed on activate) with switchable injected
 * failures and pauses, plus Better Auth database hooks that fail the plugin's own writes on
 * demand. Pass `faults` to `createTestAuth` for the adapter-level account update faults.
 */
export function createPayloadApp() {
  const payloads = new Map<string, unknown>();
  const faults = new Set<FaultPoint>();
  const pauses = new Map<PausePoint, () => Promise<void>>();

  const failIfInjected = (point: FaultPoint) => {
    if (faults.has(point)) {
      throw new Error(`injected failure: ${point}`);
    }
  };

  const hooks: OpaqueHooks = {
    validatePayload: ({ payload }) => {
      failIfInjected("validatePayload");
      if (typeof payload === "object" && payload !== null && "invalid" in payload) {
        throw new Error("payload rejected by the app");
      }
    },
    commitPayload: async ({ userId, credentialVersion, payload }) => {
      await pauses.get("commitPayload")?.();
      failIfInjected("commitPayload");
      payloads.set(`${userId}:${credentialVersion}`, payload);
    },
    activatePayload: ({ userId, previousCredentialVersion }) => {
      failIfInjected("activatePayload");
      if (previousCredentialVersion !== null) {
        payloads.delete(`${userId}:${previousCredentialVersion}`);
      }
    },
    loadPayload: async ({ userId, credentialVersion }) => {
      await pauses.get("loadPayload")?.();
      failIfInjected("loadPayload");
      return payloads.get(`${userId}:${credentialVersion}`) ?? null;
    },
  };

  const databaseHooks: BetterAuthOptions["databaseHooks"] = {
    user: { create: { before: async () => failIfInjected("user.create") } },
    account: {
      create: {
        before: async () => {
          failIfInjected("account.create");
          if (faults.has("account.create.rejected")) {
            return false;
          }
        },
      },
    },
    session: { create: { before: async () => failIfInjected("session.create") } },
  };

  return { payloads, faults, pauses, hooks, databaseHooks };
}
